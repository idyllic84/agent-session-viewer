"""Cloud API key storage for the local Web Server.

Preferred: the operating-system credential store (Windows Credential Manager,
macOS Keychain, Secret Service). Fallback: an owner-only file in the local
state directory. The SQLite store only keeps a *reference* ("keyring:..." or
"file:..."), never the key. Keys are never logged or returned to the browser.
"""
import os
from pathlib import Path
import secrets
import sys

SERVICE = 'agent-session-viewer'


def _platform_keyring():
    try:
        if sys.platform == 'win32':
            from keyring.backends.Windows import WinVaultKeyring
            return WinVaultKeyring()
        if sys.platform == 'darwin':
            from keyring.backends.macOS import Keyring
            return Keyring()
        from keyring.backends.SecretService import Keyring
        backend = Keyring()
        backend.priority  # raises when no Secret Service/DBus is usable
        return backend
    except Exception:
        return None


def key_hint(key):
    """Non-secret identifier shown in the console (key ID only)."""
    parts = key.split('_', 2)
    return parts[0] + '_' + parts[1] if len(parts) >= 3 and parts[0] == 'asv' else 'custom key'


def validate_key(key):
    if not isinstance(key, str) or not 20 <= len(key) <= 512 or any(c.isspace() or ord(c) < 33 for c in key):
        raise ValueError('Paste the complete API key generated by the cloud console')
    return key


class CredentialStore:
    def __init__(self, directory, backend='auto'):
        if backend not in ('auto', 'keyring', 'file'):
            raise ValueError('Credential backend must be auto, keyring or file')
        self.directory = Path(directory); self.backend = backend

    def _keyring(self):
        return None if self.backend == 'file' else _platform_keyring()

    def save(self, key):
        """Store a NEW credential and return its reference; old refs stay until deleted."""
        validate_key(key); name = 'cloud-api-key-' + secrets.token_hex(8)
        ring = self._keyring()
        if ring is not None:
            try:
                ring.set_password(SERVICE, name, key)
                if ring.get_password(SERVICE, name) == key:
                    return 'keyring:' + name
            except Exception:
                pass
            if self.backend == 'keyring':
                raise RuntimeError('Operating-system credential store is unavailable')
        self.directory.mkdir(parents=True, exist_ok=True)
        path = self.directory / (name + '.key')
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(key); stream.flush(); os.fsync(stream.fileno())
        return 'file:' + path.name

    def load(self, ref):
        kind, _, name = (ref or '').partition(':')
        if kind == 'keyring':
            ring = _platform_keyring()
            value = ring.get_password(SERVICE, name) if ring is not None else None
            if not value:
                raise LookupError('Saved API key is missing from the credential store; enter it again')
            return value
        if kind == 'file' and name and Path(name).name == name:
            try:
                return (self.directory / name).read_text(encoding='utf-8').strip()
            except FileNotFoundError:
                raise LookupError('Saved API key file is missing; enter it again') from None
        raise LookupError('No API key saved')

    def delete(self, ref):
        kind, _, name = (ref or '').partition(':')
        try:
            if kind == 'keyring':
                ring = _platform_keyring()
                if ring is not None:
                    ring.delete_password(SERVICE, name)
            elif kind == 'file' and name and Path(name).name == name:
                (self.directory / name).unlink(missing_ok=True)
        except Exception:
            pass

    def describe(self, ref):
        kind = (ref or '').partition(':')[0]
        return {'keyring': 'operating-system credential store', 'file': 'owner-only local key file'}.get(kind, 'none')
